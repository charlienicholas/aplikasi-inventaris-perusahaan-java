    private void btnEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditActionPerformed
        int stokTerbaca;
        try {
            stokTerbaca = Integer.parseInt(txtStokBarang.getText().trim());
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Perubahan ditolak! Nilai STOK wajib bertipe angka!");
            return;
        }
        try {
            String sql = "UPDATE stok_persediaan SET jenis_barang=?, nama_barang=?, stok_barang=? WHERE kode_barang=?";
            Connection conn = Koneksi.getKoneksi();
            PreparedStatement pst = conn.prepareStatement(sql);
            pst.setString(1, txtJenisBarang.getText().trim());
            pst.setString(2, txtNamaBarang.getText().trim());
            pst.setInt(3, stokTerbaca);
            pst.setString(4, txtKodeBarang.getText().trim());
            pst.executeUpdate();
            JOptionPane.showMessageDialog(null, "Perbaruan data stok persediaan berhasil.");
            tampilData();
            resetForm();
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Proses edit data gagal: " +
                e.getMessage());
            }
    }//GEN-LAST:event_btnEditActionPerformed

    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
        if (txtKodeBarang.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Pilih baris data pada tabel terlebih dahulu!");
            return;
        }
        int konfirmasi = JOptionPane.showConfirmDialog(this, "Apakah Anda yakin ingin menghapus aset ini?", "Konfirmasi", JOptionPane.YES_NO_OPTION);
        if (konfirmasi == JOptionPane.YES_OPTION) {
            try {
                String sql = "DELETE FROM stok_persediaan WHERE kode_barang=?";
                Connection conn = Koneksi.getKoneksi();
                PreparedStatement pst = conn.prepareStatement(sql);
                pst.setString(1, txtKodeBarang.getText().trim());
                pst.executeUpdate();
                JOptionPane.showMessageDialog(null, "Data barang berhasil dihapus dari sistem.");
                tampilData();
                resetForm();
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Gagal menghapus data: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_btnHapusActionPerformed

