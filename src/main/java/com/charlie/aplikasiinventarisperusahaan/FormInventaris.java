    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
        // Validasi input data kosong
        if (txtKodeBarang.getText().trim().isEmpty() || txtNamaBarang.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Kode dan Nama Barang tidak boleh kosong!");
            return;
        }
        
        // Logika Validasi Angka Murni pada kolom stok untuk mencegah crash aplikasi
        int stokTerbaca;
        try {
            stokTerbaca = Integer.parseInt(txtStokBarang.getText().trim());
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Input tidak valid! Kolom STOK BARANG harus diisi angka murni!");
            return; // Menghentikan eksekusi kueri SQL
        }
        
        try {
            String sql = "INSERT INTO stok_persediaan (kode_barang, jenis_barang, nama_barang, stok_barang) VALUES (?, ?, ?, ?)";
            Connection conn = Koneksi.getKoneksi();
            PreparedStatement pst = conn.prepareStatement(sql);
            pst.setString(1, txtKodeBarang.getText().trim());
            pst.setString(2, txtJenisBarang.getText().trim());
            pst.setString(3, txtNamaBarang.getText().trim());
            pst.setInt(4, stokTerbaca);
            pst.execute();
            JOptionPane.showMessageDialog(null, "Data inventori baru berhasil disimpan.");
            tampilData();
            resetForm();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Gagal menyimpan data: " + e.getMessage());
        }
    }//GEN-LAST:event_btnSimpanActionPerformed

    private void tblInventarisMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblInventarisMouseClicked
        int baris = tblInventaris.rowAtPoint(evt.getPoint());
        txtKodeBarang.setText(tblInventaris.getValueAt(baris, 0).toString());
        txtJenisBarang.setText(tblInventaris.getValueAt(baris, 1).toString());
        txtNamaBarang.setText(tblInventaris.getValueAt(baris, 2).toString());
        txtStokBarang.setText(tblInventaris.getValueAt(baris, 3).toString());
        // Mengunci kolom kode_barang agar primary key tidak diubah sembarangan saat edit
        txtKodeBarang.setEditable(false);
    }//GEN-LAST:event_tblInventarisMouseClicked

